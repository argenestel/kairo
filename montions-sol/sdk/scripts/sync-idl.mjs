// Re-copy the Anchor IDL + TS types from ../target into src/idl/ (run after `anchor build`).
// Usage: pnpm sync-idl   (from montions-sol/sdk)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const out = join(here, '..', 'src', 'idl');
mkdirSync(out, { recursive: true });

const idlText = readFileSync(join(root, 'target', 'idl', 'montions.json'), 'utf8');
const idl = JSON.parse(idlText);
const types = readFileSync(join(root, 'target', 'types', 'montions.ts'), 'utf8');

writeFileSync(join(out, 'montions.json'), idlText);
writeFileSync(join(out, 'montions-types.ts'), types);
writeFileSync(
  join(out, 'index.ts'),
  `// GENERATED by scripts/sync-idl.mjs from target/idl/montions.json — do not edit.\n` +
    `import type { Montions } from './montions-types.js';\n` +
    `export type { Montions } from './montions-types.js';\n\n` +
    `/** Raw Anchor IDL (snake_case names, as emitted by anchor 0.32). */\n` +
    `export const IDL: Montions = ${JSON.stringify(idl, null, 2)} as unknown as Montions;\n`,
);
console.log(`synced IDL ${idl.metadata?.name}@${idl.metadata?.version} (${idl.instructions.length} instructions) -> src/idl/`);
